#!/usr/bin/env python3
"""The emulator's menu font: Inter (SIL OFL 1.1) rendered with smooth edges into a C header.

    make_font.py FONT_DIR OUT.h

Each face: the printable ASCII, the Polish letters and a few signs, each glyph an 8-bit coverage
bitmap with its place against the baseline and its advance."""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

font_dir, out = sys.argv[1:3]
TEXT = [chr(c) for c in range(32, 127)] + list("ąćęłńóśźżĄĆĘŁŃÓŚŹŻ…•›‹▲▼◀▶·×–—°●○")
FACES = [   # name, file, size px, the characters (None: all)
    ("small", "Inter-Medium", 15, None),
    ("body", "Inter-Regular", 19, None),
    ("list", "Inter-Medium", 23, None),
    ("title", "Inter-SemiBold", 28, None),
    ("huge", "Inter-Bold", 60, list("0123456789 NES-")),
]


def find(name):
    for ext in (".otf", ".ttf"):
        for root, _d, files in os.walk(font_dir):
            if name + ext in files:
                return os.path.join(root, name + ext)
    raise SystemExit("font not found: %s in %s" % (name, font_dir))


data = bytearray()
lines = ["/* Generated by make_font.py from Inter (SIL Open Font License 1.1, https://rsms.me/inter). */",
         "struct glyph { uint16_t cp; uint8_t w, h; int8_t x, y; uint8_t adv; uint32_t off; };",
         "struct face { const struct glyph *g; int n, ascent, height; };"]
faces = []
for name, file, size, chars in FACES:
    font = ImageFont.truetype(find(file), size)
    ascent, descent = font.getmetrics()
    glyphs = []
    for ch in sorted(set(chars or TEXT), key=ord):
        adv = int(round(font.getlength(ch)))
        box = font.getbbox(ch, anchor="ls")          # against the baseline
        if not box or box[2] <= box[0] or box[3] <= box[1]:
            glyphs.append((ord(ch), 0, 0, 0, 0, adv, len(data)))
            continue
        w, h = box[2] - box[0], box[3] - box[1]
        im = Image.new("L", (w, h), 0)
        ImageDraw.Draw(im).text((-box[0], -box[1]), ch, font=font, fill=255, anchor="ls")
        off = len(data)
        data += im.tobytes()
        glyphs.append((ord(ch), w, h, box[0], box[1], adv, off))
    lines.append("static const struct glyph glyphs_%s[] = {" % name)
    for g in glyphs:
        lines.append("\t{%d, %d, %d, %d, %d, %d, %d}," % g)
    lines.append("};")
    faces.append("\t{glyphs_%s, %d, %d, %d}," % (name, len(glyphs), ascent, ascent + descent))
lines.append("static const uint8_t font_px[%d] = {" % len(data))
for i in range(0, len(data), 32):
    lines.append("\t" + ",".join(str(b) for b in data[i:i + 32]) + ",")
lines.append("};")
lines.append("enum { F_SMALL, F_BODY, F_LIST, F_TITLE, F_HUGE };")
lines.append("static const struct face faces[] = {")
lines += faces
lines.append("};")
open(out, "w").write("\n".join(lines) + "\n")
print("%s: %d glyph bytes" % (out, len(data)))
